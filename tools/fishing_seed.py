"""Build addons/StraightHook/Data/Seed.lua from reference/fishing/*.csv (Classic fishing priors; StraightHook D-006).

  uv run --no-project python tools/fishing_seed.py
"""
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "reference" / "fishing"
OUT = ROOT / "addons" / "StraightHook" / "Data" / "Seed.lua"


def main() -> None:
    loot: dict[int, list] = defaultdict(list)
    for r in csv.DictReader(open(REF / "classic_fishing_loot.csv")):
        pct = float(r["pct"])
        if pct <= 0:
            continue
        loot[int(r["area_id"])].append((int(r["item_id"]), pct, int(r["group"]), r["kind"]))
    base = {int(r["area_id"]): int(r["base"]) for r in csv.DictReader(open(REF / "classic_fishing_skill.csv"))}
    zone = {int(r["area_id"]): int(r["zone_id"]) for r in csv.DictReader(open(REF / "classic_fishing_areas.csv"))}
    lines = ["-- Generated by tools/fishing_seed.py from reference/fishing (see its README for source and licence).",
             "-- Classic fishing priors derived from CMaNGOS classic-db (GPL-3.0), https://github.com/cmangos/classic-db",
             "-- areas[areaID] = { zone = parent zone areaID (subzones only), base = fishing level, loot = { {itemID, pct, group, kind}, ... } }",
             "local _, ns = ...", "ns.SEED = {", '  source = "CMaNGOS classic-db e4825cf (1.12)",', "  areas = {"]
    for area in sorted(set(loot) | set(base)):
        rows = sorted(loot.get(area, []), key=lambda x: (-x[1], x[0]))
        parts = []
        if zone.get(area, area) != area:
            parts.append(f"zone = {zone[area]}")
        if area in base:
            parts.append(f"base = {base[area]}")
        if rows:
            items = ", ".join("{%d, %s, %d%s}" % (i, f"{p:g}", g, f', "{k}"' if k else "") for i, p, g, k in rows)
            parts.append("loot = { " + items + " }")
        lines.append(f"    [{area}] = {{ {', '.join(parts)} }},")
    lines += ["  },", "}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(set(loot) | set(base))} areas, {sum(map(len, loot.values()))} rows")


if __name__ == "__main__":
    main()
